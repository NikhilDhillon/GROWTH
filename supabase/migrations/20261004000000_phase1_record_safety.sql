create or replace function public.replace_score_snapshots(p_snapshots jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  publishing_user uuid := auth.uid();
  snapshot jsonb;
begin
  if publishing_user is null then raise exception 'Please log in again.'; end if;
  if p_snapshots is null or jsonb_typeof(p_snapshots) <> 'array' then raise exception 'Score snapshots must be an array.'; end if;
  perform pg_advisory_xact_lock(hashtextextended('growth:snapshots:' || publishing_user::text, 0));
  delete from public.leaderboard_score_snapshots where user_id = publishing_user;
  for snapshot in select value from jsonb_array_elements(p_snapshots) loop
    if jsonb_typeof(snapshot) <> 'object' or jsonb_typeof(snapshot->'best_score') is distinct from 'number'
      or (snapshot->>'best_score')::numeric < 0 or jsonb_typeof(snapshot->'best_sets') is distinct from 'array'
      or nullif(snapshot->>'exercise_name', '') is null then raise exception 'Invalid score snapshot.'; end if;
    insert into public.leaderboard_score_snapshots (user_id, exercise_id, exercise_name, best_score, best_sets, achieved_at, updated_at)
    values (publishing_user, (snapshot->>'exercise_id')::bigint, snapshot->>'exercise_name',
      (snapshot->>'best_score')::numeric, snapshot->'best_sets', (snapshot->>'achieved_at')::date, now());
  end loop;
end;
$$;

create or replace function public.save_active_workout(p_active_workout jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  recording_user uuid := auth.uid();
  active_record jsonb;
  workout_id_value text;
begin
  if recording_user is null then raise exception 'Please log in again.'; end if;
  if p_active_workout is null or jsonb_typeof(p_active_workout) <> 'object'
    or jsonb_typeof(p_active_workout->'startedAt') is distinct from 'string'
    or nullif(trim(p_active_workout->>'startedAt'), '') is null then
    raise exception 'An active workout with its original identifier is required.';
