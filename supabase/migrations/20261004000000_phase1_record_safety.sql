    and active_record->>'startedAt' is distinct from workout_id_value then
    raise exception 'A different workout is active. This request did not change it.';
  end if;
  insert into public.app_settings (user_id, key, value, updated_at)
  values (recording_user, 'active_workout', p_active_workout::text, now())
  on conflict (user_id, key) do update set value = excluded.value, updated_at = excluded.updated_at;
end;
