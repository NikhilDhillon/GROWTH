create or replace function public.request_split_sync(friend_id uuid, split_days jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  editing_user uuid := auth.uid();
  editor_name text;
begin
  if editing_user is null then raise exception 'Please log in again.'; end if;
  if split_days is null or jsonb_typeof(split_days) <> 'array' then
    raise exception 'Training split days must be an array.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));
  if not exists (
    select 1 from public.friendships where status = 'accepted'
      and user_low = least(editing_user, friend_id) and user_high = greatest(editing_user, friend_id)
  ) then raise exception 'Split synchronization can only be requested from an accepted friend.'; end if;

  select coalesce(nullif(trim(name), ''), split_part(email, '@', 1), 'User') into editor_name
  from public.profiles where id = editing_user;
  insert into public.shared_training_splits (user_id, split_days, updated_by, updated_by_name, updated_at)
  values (editing_user, split_days, editing_user, coalesce(editor_name, 'User'), now())
  on conflict (user_id) do nothing;

  insert into public.split_sync_requests (requester_id, addressee_id, status, updated_at)
  values (editing_user, friend_id, 'pending', now())
  on conflict (user_low, user_high) do update set
    requester_id = excluded.requester_id, addressee_id = excluded.addressee_id,
    status = 'pending', updated_at = excluded.updated_at;
end;
$$;

create or replace function public.respond_split_sync(request_id uuid, accept_request boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  receiving_user uuid := auth.uid();
  request_row public.split_sync_requests%rowtype;
begin
  if receiving_user is null then raise exception 'Please log in again.'; end if;
  if accept_request is null then raise exception 'A response is required.'; end if;
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));
  select * into request_row from public.split_sync_requests
  where id = request_id and addressee_id = receiving_user and status = 'pending' for update;
  if request_row.id is null then raise exception 'This split synchronization request is not available.'; end if;
  if not exists (
    select 1 from public.friendships where status = 'accepted'
      and user_low = request_row.user_low and user_high = request_row.user_high
  ) then raise exception 'Split synchronization requires an accepted friendship.'; end if;

  update public.split_sync_requests set status = case when accept_request then 'accepted' else 'declined' end,
    updated_at = now() where id = request_id;
  if accept_request then
    insert into public.shared_training_splits (user_id, split_days, updated_by, updated_by_name, updated_at)
    select receiving_user, split_days, updated_by, updated_by_name, updated_at
    from public.shared_training_splits where user_id = request_row.requester_id
    on conflict (user_id) do update set split_days = excluded.split_days, updated_by = excluded.updated_by,
      updated_by_name = excluded.updated_by_name, updated_at = excluded.updated_at;
  end if;
end;
$$;

create or replace function public.remove_split_sync(friend_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  removing_user uuid := auth.uid();
begin
  if removing_user is null then raise exception 'Please log in again.'; end if;
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));
  -- Retain an explicit opt-out. Deleting this edge alone would allow the same
  -- pair to keep receiving each other's edits through a third synchronized user.
  if exists (
    select 1 from public.friendships where status = 'accepted'
      and user_low = least(removing_user, friend_id) and user_high = greatest(removing_user, friend_id)
  ) then
    insert into public.split_sync_requests (requester_id, addressee_id, status, updated_at)
    values (removing_user, friend_id, 'declined', now())
    on conflict (user_low, user_high) do update set status = 'declined', updated_at = excluded.updated_at;
  else
    update public.split_sync_requests set status = 'declined', updated_at = now()
    where user_low = least(removing_user, friend_id) and user_high = greatest(removing_user, friend_id);
  end if;
end;
$$;

create or replace function public.save_shared_training_split(split_days jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  editing_user uuid := auth.uid();
  editor_name text;
begin
  if editing_user is null then raise exception 'Please log in again.'; end if;
  if split_days is null or jsonb_typeof(split_days) <> 'array' then
    raise exception 'Training split days must be an array.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));
  select coalesce(nullif(trim(name), ''), split_part(email, '@', 1), 'User') into editor_name
  from public.profiles where id = editing_user;

  insert into public.shared_training_splits (user_id, split_days, updated_by, updated_by_name, updated_at)
  with recursive synchronized_users(user_id) as (
    select editing_user
    union
    select case when request.requester_id = group_user.user_id then request.addressee_id else request.requester_id end
    from synchronized_users group_user
    join public.split_sync_requests request on request.status = 'accepted'
      and group_user.user_id in (request.requester_id, request.addressee_id)
    join public.friendships friendship on friendship.status = 'accepted'
      and friendship.user_low = request.user_low and friendship.user_high = request.user_high
  )
  select user_id, split_days, editing_user, coalesce(editor_name, 'User'), now()
  from synchronized_users group_user
  where group_user.user_id = editing_user or (exists (
    select 1 from public.friendships where status = 'accepted'
      and user_low = least(editing_user, group_user.user_id)
      and user_high = greatest(editing_user, group_user.user_id)
  ) and not exists (
    select 1 from public.split_sync_requests where status <> 'accepted'
      and user_low = least(editing_user, group_user.user_id)
      and user_high = greatest(editing_user, group_user.user_id)
  ))
  on conflict (user_id) do update set split_days = excluded.split_days, updated_by = excluded.updated_by,
    updated_by_name = excluded.updated_by_name, updated_at = excluded.updated_at;
end;
$$;

create or replace function public.save_workout_session(
  p_exercise_id bigint, p_workout_date date, p_notes text, p_machine_profile_id text,
  p_sets jsonb, p_session_id bigint default null, p_request_id uuid default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  recording_user uuid := auth.uid();
  saved_session public.workout_sessions%rowtype;
  receipt public.workout_write_requests%rowtype;
  normalized_sets jsonb;
  input_hash text;
  row_value jsonb;
  set_index integer := 0;
  timestamp_value timestamptz;
begin
  if recording_user is null then raise exception 'Please log in again.'; end if;
  if p_exercise_id is null or p_workout_date is null then raise exception 'An exercise and workout date are required.'; end if;
  if p_sets is null or jsonb_typeof(p_sets) <> 'array' or jsonb_array_length(p_sets) = 0 then
    raise exception 'At least one observed set is required.';
  end if;
  if p_session_id is not null and p_request_id is not null then raise exception 'Create request IDs cannot be used for editing.'; end if;
  for row_value in select value from jsonb_array_elements(p_sets) loop
    if jsonb_typeof(row_value) <> 'object' or jsonb_typeof(row_value->'reps') is distinct from 'number'
      or jsonb_typeof(row_value->'weight') is distinct from 'number'
      or (row_value->>'reps')::numeric <= 0 or (row_value->>'reps')::numeric <> trunc((row_value->>'reps')::numeric)
      or (row_value->>'weight')::numeric < 0
      or (row_value ? 'isWarmup' and jsonb_typeof(row_value->'isWarmup') <> 'boolean') then
      raise exception 'Observed sets require positive whole reps, non-negative weight and a valid warm-up flag.';
    end if;
  end loop;
  select jsonb_agg(jsonb_build_object('reps', (value->>'reps')::numeric::integer, 'weight', trim_scale((value->>'weight')::numeric),
    'isWarmup', coalesce((value->>'isWarmup')::boolean, false)) order by ordinal)
  into normalized_sets from jsonb_array_elements(p_sets) with ordinality as input(value, ordinal);
  input_hash := encode(sha256(convert_to(jsonb_build_object('exerciseId', p_exercise_id, 'workoutDate', p_workout_date,
    'notes', p_notes, 'machineProfileId', p_machine_profile_id, 'sets', normalized_sets)::text, 'UTF8')), 'hex');

  perform pg_advisory_xact_lock(hashtextextended('growth:workouts:' || recording_user::text, 0));
  if p_request_id is not null then
    select * into receipt from public.workout_write_requests where user_id = recording_user and request_id = p_request_id;
    if found then
      if receipt.payload_hash <> input_hash then raise exception 'This save request was already used for different observations.'; end if;
      if receipt.session_id is null then raise exception 'This saved workout was deleted. Start a new recording to save new work.'; end if;
      return receipt.session_id;
    end if;
  end if;

  if p_session_id is null then
    timestamp_value := (p_workout_date::text || 'T12:00:00Z')::timestamptz;
    insert into public.workout_sessions (user_id, workout_date, notes, machine_profile_id, created_at)
    values (recording_user, p_workout_date, p_notes, p_machine_profile_id, timestamp_value)
    returning * into saved_session;
  else
    select * into saved_session from public.workout_sessions where id = p_session_id and user_id = recording_user for update;
    if not found then raise exception 'This workout is unavailable or does not belong to you.'; end if;
    timestamp_value := saved_session.created_at;
    update public.workout_sessions set workout_date = p_workout_date, notes = p_notes, machine_profile_id = p_machine_profile_id
    where id = saved_session.id;
    delete from public.workout_sets where session_id = saved_session.id;
  end if;

  for row_value in select value from jsonb_array_elements(normalized_sets) loop
    set_index := set_index + 1;
    insert into public.workout_sets (user_id, session_id, exercise_id, set_number, reps, weight, rir, is_warmup, created_at)
    values (recording_user, saved_session.id, p_exercise_id, set_index, (row_value->>'reps')::integer,
      (row_value->>'weight')::numeric, 0, (row_value->>'isWarmup')::boolean, timestamp_value);
  end loop;
  if p_request_id is not null then
    insert into public.workout_write_requests (user_id, request_id, payload_hash, session_id)
    values (recording_user, p_request_id, input_hash, saved_session.id);
  end if;
  return saved_session.id;
end;
$$;

