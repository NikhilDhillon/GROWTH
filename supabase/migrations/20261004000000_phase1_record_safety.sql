create or replace function public.cleanup_revoked_friendship()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- This also covers service/admin deletion and accepted -> non-accepted edits.
  if tg_op = 'DELETE' or (old.status = 'accepted' and new.status <> 'accepted') then
    delete from public.split_sync_requests
    where user_low = old.user_low and user_high = old.user_high;
  end if;
  return null;
end;
$$;
revoke all on function public.cleanup_revoked_friendship() from public, anon, authenticated;
drop trigger if exists cleanup_revoked_friendship on public.friendships;
create trigger cleanup_revoked_friendship
  after delete or update of status on public.friendships
  for each row execute function public.cleanup_revoked_friendship();

create or replace function public.accept_friend_invite(invite_token text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  invite_row public.friend_invites%rowtype;
  accepting_user uuid := auth.uid();
begin
  if accepting_user is null then raise exception 'Please log in again.'; end if;
  -- Relationship mutations and propagation are rare. One transaction lock
  -- keeps consent/revocation and recursive shared-plan writes serialized.
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));

  select * into invite_row from public.friend_invites
  where token = invite_token for update;
  if invite_row.id is null then raise exception 'This invite is expired or has already been used.'; end if;
  if invite_row.owner_id = accepting_user then raise exception 'You cannot accept your own invite.'; end if;

  if invite_row.accepted_by = accepting_user and exists (
    select 1 from public.friendships where status = 'accepted'
      and user_low = least(invite_row.owner_id, accepting_user)
      and user_high = greatest(invite_row.owner_id, accepting_user)
  ) then return; end if;

  if invite_row.accepted_by is not null or invite_row.expires_at <= now() then
    raise exception 'This invite is expired or has already been used.';
  end if;

  insert into public.friendships (requester_id, addressee_id, status)
  values (invite_row.owner_id, accepting_user, 'accepted')
  on conflict (user_low, user_high)
  do update set status = 'accepted', updated_at = now();

  update public.friend_invites set accepted_by = accepting_user where id = invite_row.id;
end;
$$;

