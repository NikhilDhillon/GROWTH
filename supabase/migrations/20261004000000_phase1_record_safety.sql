-- Shared-catalog authority must not guess or erase legacy exercise ownership.
do $$
begin
  if to_regclass('public.exercises') is not null then
    if exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'exercises' and column_name = 'user_id'
    ) then
      raise exception 'Legacy exercise ownership must be reconciled explicitly before applying Phase 1. All existing data is preserved.';
    end if;
    if exists (select 1 from public.exercises group by name having count(*) > 1) then
      raise exception 'Duplicate exercise names require explicit reconciliation. All existing data is preserved.';
    end if;
  end if;
  if to_regclass('public.workout_sets') is not null and not exists (
    select 1 from pg_constraint foreign_key
    join pg_attribute session_column on session_column.attrelid = foreign_key.conrelid and session_column.attname = 'session_id'
    join pg_attribute id_column on id_column.attrelid = foreign_key.confrelid and id_column.attname = 'id'
    where foreign_key.contype = 'f' and foreign_key.convalidated
      and foreign_key.conrelid = to_regclass('public.workout_sets')
      and foreign_key.confrelid = to_regclass('public.workout_sessions')
      and foreign_key.conkey = array[session_column.attnum]
      and foreign_key.confkey = array[id_column.attnum]
      and foreign_key.confdeltype = 'c'
  ) then
    raise exception 'Workout history requires a verified ON DELETE CASCADE session foreign key before applying Phase 1. All existing data is preserved.';
  end if;
end;
$$;

