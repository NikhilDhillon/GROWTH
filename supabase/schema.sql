create or replace function public.lock_relationship_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Statement triggers serialize service/admin mutations too, before they
  -- acquire row locks. RPCs take the same reentrant transaction lock.
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));
  return null;
end;
$$;
