    updated_at timestamptz not null default now(),
    unique (user_id, logged_date)
  );

  if not modern_table_existed then
    insert into public.body_measurement_logs (user_id, weight, measurements, logged_date, created_at, updated_at)
    select legacy.user_id, legacy.weight, '{}'::jsonb, legacy.logged_date, legacy.created_at, legacy.created_at
    from public.body_weight_logs legacy
    where not exists (
      select 1 from public.app_settings settings
      where settings.user_id = legacy.user_id and settings.key = 'body_measurements_legacy_migrated'
    )
    on conflict (user_id, logged_date) do nothing;
  end if;

  insert into public.app_settings (user_id, key, value)
  select id, 'body_measurements_legacy_migrated',
    case when modern_table_existed then 'existing_modern_legacy_preserved' else 'migrated_legacy' end
