create or replace function public.save_shared_training_split(split_days jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  editing_user uuid := auth.uid();
  editor_name text;
begin
  if editing_user is null then raise exception 'Please log in again.'; end if;
  if split_days is null or jsonb_typeof(split_days) <> 'array' then
    raise exception 'Training split days must be an array.';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('growth:relationships', 0));
  select coalesce(nullif(trim(name), ''), split_part(email, '@', 1), 'User') into editor_name
  from public.profiles where id = editing_user;

  insert into public.shared_training_splits (user_id, split_days, updated_by, updated_by_name, updated_at)
  with recursive synchronized_users(user_id) as (
    select editing_user
    union
    select case when request.requester_id = group_user.user_id then request.addressee_id else request.requester_id end
    from synchronized_users group_user
    join public.split_sync_requests request on request.status = 'accepted'
      and group_user.user_id in (request.requester_id, request.addressee_id)
    join public.friendships friendship on friendship.status = 'accepted'
      and friendship.user_low = request.user_low and friendship.user_high = request.user_high
  )
  select user_id, split_days, editing_user, coalesce(editor_name, 'User'), now()
  from synchronized_users group_user
  where group_user.user_id = editing_user or (exists (
    select 1 from public.friendships where status = 'accepted'
      and user_low = least(editing_user, group_user.user_id)
      and user_high = greatest(editing_user, group_user.user_id)
  ) and not exists (
    select 1 from public.split_sync_requests where status <> 'accepted'
      and user_low = least(editing_user, group_user.user_id)
      and user_high = greatest(editing_user, group_user.user_id)
  ))
  on conflict (user_id) do update set split_days = excluded.split_days, updated_by = excluded.updated_by,
    updated_by_name = excluded.updated_by_name, updated_at = excluded.updated_at;
end;
$$;

