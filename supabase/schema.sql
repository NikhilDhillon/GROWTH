-- Seed only explicit identities from valid existing archives. Invalid legacy
-- JSON remains untouched for reconciliation; never invent a workout identity.
do $$
declare
  stored_archive record;
  archived_records jsonb;
begin
  for stored_archive in select user_id, value from public.app_settings where key = 'completed_guided_workouts' loop
    begin archived_records := stored_archive.value::jsonb;
    exception when invalid_text_representation then continue; end;
    if jsonb_typeof(archived_records) <> 'array' then continue; end if;
    insert into public.active_workout_retirements (user_id, workout_id)
    select stored_archive.user_id, summary->>'startedAt'
    from jsonb_array_elements(archived_records) summary
    where jsonb_typeof(summary->'startedAt') = 'string' and nullif(trim(summary->>'startedAt'), '') is not null
    on conflict (user_id, workout_id) do nothing;
  end loop;
end;
$$;

